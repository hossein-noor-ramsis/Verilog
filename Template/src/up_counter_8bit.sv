//
// SystemVerilog description for an 8-bit Up Counter
// using a Huffman-style model for the core sequential logic
//
module up_counter_8bit (
    // Clock and Control Signals
    input logic clk,   // Falling-edge clock
    input logic arst,  // Asynchronous, Active-High Reset
    input logic ce,    // Count Enable (Active-High)
    input logic le,    // Load Enable (Active-High)
    input logic oe,    // Output Enable (Active-High, for Tri-state buffer)

    // Data and Carry Signals
    input logic       ci,          // Carry-In
    inout logic [7:0] parallel_io  // 8-bit Parallel Data Input/Output
);

  // Internal Register for the Counter Value (Q)
  logic [7:0] q_reg;

  // Internal wire for the output of the tri-state buffer
  // This is the actual counter value when oe is high, or high-impedance when oe is low
  logic [7:0] data_out_tri;


  // 1. Core Logic: Sequential Block (Huffman Model)
  // The Huffman model combines asynchronous reset and synchronous state update
  // in a single always_ff block for synthesis predictability.
  always_ff @(negedge clk or posedge arst) begin
    if (arst) begin
      // Asynchronous, Active-High Reset
      q_reg <= 8'h00;
    end else begin
      // Synchronous Logic (on falling edge of clk)
      if (le) begin
        // Load Operation (Highest priority synchronous action)
        // Use the input value from the inout port
        q_reg <= parallel_io;
      end else if (ce) begin
        // Count Operation (Next priority)
        // q_reg + 1 + carry_in
        q_reg <= q_reg + ci + 1'b1;
      end
      // else (ce is low and le is low), the counter holds its current value (q_reg <= q_reg)
    end
  end


  // 2. Combinational Logic: Carry-Out Generation
  // Carry_out is high when the counter is at its maximum value (8'hFF) AND the count is enabled (ce)
  // AND there is a carry-in (ci). Since this is an Up counter, the carry-out is simply the 
  // carry generated by the addition when count is enabled.
  // A simpler way: The MSB carry-out from the adder logic.
  // For a simple increment: carry_out is the 9th bit of the addition.
  // (q_reg + ci + 1'b1) is a 9-bit result.

  logic [8:0] next_q_add;

  // This calculates the result of the count operation (q_reg + 1 + ci)
  assign next_q_add  = {1'b0, q_reg} + ci + 1'b1;

  // The carry_out is the MSB (bit 8) of the addition result, 
  // BUT it only matters if the count enable (ce) is active.
  assign carry_out   = ce & next_q_add[8];


  // 3. Combinational Logic: Tri-state Buffer Control
  // The inout port is used for both parallel loading (input) and counter output (output).
  // The output is driven when the Output Enable (oe) is active high.
  // When oe is low, the port is high-impedance (z).
  // When le is high, the port is also used for input, but the assign statement handles the output drive.

  // Output assignment using a conditional operator for tri-state control
  assign parallel_io = (oe) ? q_reg : 8'bz;


endmodule
